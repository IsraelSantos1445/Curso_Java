

public class DataType {
    static void main() {
        //tipos de datos
        //PRIMITIVOS

        //numeros enteros
        int myInt = 67;
        System.out.println(myInt);
        //numeros decimales TAMBIEN EXISTEN SHORT LONG Y FLOAT
        double myDouble=3.1416;
        System.out.println(myDouble);
        //Un solo caracter SE USA CON COMILLAS SIMPLES
        char myChar='a';
        System.out.println(myChar);
        //Verdadero o falso
        boolean MyBoolean=true;
        //string no es dato primitivo pero se usa como dato primitivo
        String MyString="Hola Java";
        System.out.println(MyString);

        //TIPO DE DATO EN TIEMPO DE COMPILACION



    }
}
